function session(id: string, endedAt: string): TrainingSession {
  return {
    id,
    coachId: 'coach-1',
    mode: 'tecnico',
    spotId: 'spot-1',
    spotName: 'Beach',
    condition: 'Clean',
    startedAt: endedAt,
    endedAt,
    athleteIds: ['a1'],
    waves: [],
    comboEntries: [],
    heats: [],
    seaAnalysis: null,
    coachNotes: null,
  }
}

function feedback(sessionId: string, submittedAt: string): SessionAthleteFeedback {
  return {
    id: `fb-${sessionId}`,
    sessionId,
    athleteId: 'a1',
    coachId: 'coach-1',
    psychologyScores: {
      ...createDefaultPsychologySurveyScores(),
      mood: 5,
      focusDuring: 2,
    },
    writtenNote: 'Felt focused after the session.',
    submittedAt,
  }
}

describe('buildAthleteReportPdfBlob psychology', () => {
  it('embeds psychology questionnaire results in the PDF', async () => {
    const sessions = [session('s1', '2026-07-20T12:00:00.000Z')]
    const psychology = buildAthletePsychologyAnalytics(
      [feedback('s1', '2026-07-20T12:30:00.000Z')],
      sessions,
      'coach-1',
      'a1',
      customAnalyticsRange('2026-07-01', '2026-07-31'),
    )

    const input: AthleteReportPdfInput = {
      athleteName: 'Test Athlete',
      coachName: 'Coach',
      rangeLabel: 'Jul 2026',
      reportTitle: 'July report',
      generatedAt: '2026-07-31 10:00',
      footerLine: 'Generated by SurfStar',
      general: {
        totalTrainings: 1,
        totalWaves: 0,
        withPotential: 0,
        withoutPotential: 0,
        withPotentialRate: null,
        withoutPotentialRate: null,
        heatWins: 0,
        heatParticipations: 0,
        championshipWins: 0,
        avgHeatScore: null,
        totalStars: 0,
        technicalStars: 0,
        comboStars: 0,
        avgTechnicalManeuverLevel: null,
        avgComboLevel: null,
        avgOverallManeuverLevel: null,
        totalManeuverAttempts: 0,
        technicalAttemptCount: 0,
        comboAttemptCount: 0,
      },
      evolution: [],
      evolutionColumnLabel: 'Week',
      evolutionCharts: {
        periodLabels: [],
        potentialRates: [],
        maneuverSeries: [],
        comboSuccessRates: [],
        comboAvgLevels: [],
      },
      maneuverLabels: {},
      technicalSideCharts: [],
      comboSideCharts: [],
      trainingMix: [],
      technical: null,
      combo: null,
      psychology,
      maneuverSummaries: [],
      sessionRows: [],
      labels,
    }

    const blob = await buildAthleteReportPdfBlob(input)
    const bytes = Buffer.from(await blob.arrayBuffer())
    const asLatin1 = bytes.toString('latin1')

    expect(psychology.checkIns).toBe(1)
    expect(asLatin1).toContain('Psychology check-ins')
    expect(asLatin1).toContain('Standouts')
    expect(asLatin1).toContain('Question averages')
    expect(asLatin1).toContain('Athlete notes')
    expect(asLatin1).toContain('Felt focused after the session.')
  })
})
